class TlsBuildError(Exception):
    pass


def fetch_bearssl(cache: Path) -> Path:
    archive = cache / BEARSSL_ARCHIVE
    if not archive.exists():
        cache.mkdir(parents=True, exist_ok=True)
        subprocess.run(["curl", "-fL", "--retry", "3", "-o", str(archive), BEARSSL_URL], check=True)
    digest = hashlib.sha256(archive.read_bytes()).hexdigest()
    if digest != BEARSSL_SHA256:
        archive.unlink()
        raise TlsBuildError(f"{archive.name} has SHA-256 {digest}, expected {BEARSSL_SHA256}")
    src = cache / f"bearssl-{BEARSSL_VERSION}"
    if not (src / "inc" / "bearssl.h").exists():
        with tarfile.open(archive) as tar:
            tar.extractall(cache, filter="data")
    return src


def build_brssl(src: Path) -> Path:
    brssl = src / "build" / "brssl"
    if not brssl.exists():
        subprocess.run(["make", "-C", str(src), "-j8", "build/brssl"], check=True, capture_output=True)
    return brssl


def certificate_files(root: Path) -> list[Path]:
    return sorted((root / "payload" / "certs").glob("*.pem"))


def trust_anchors_header(brssl: Path, pems) -> str:
    out = subprocess.run([str(brssl), "ta", *map(str, pems)], check=True, capture_output=True, text=True).stdout
    if "TAs_NUM" not in out:
        raise TlsBuildError("brssl ta wrote no trust anchors")
    return "/* generated by jpreader_tools.tls from payload/certs; do not edit */\n" + out


TEST_CA = Path("build") / "test-ca"


def _openssl(folder: Path, *args: str) -> None:
    subprocess.run(["openssl", *args], cwd=folder, check=True, capture_output=True)


def ensure_test_ca(root: Path) -> Path:
    """A certificate authority made once on this computer, with a certificate for localhost, for the
    emulator's stand-in kokoro (standin.py). It lives in build/test-ca, never committed; only debug
    builds trust it."""
    folder = root / TEST_CA
    if all((folder / name).exists() for name in ("ca.pem", "server.pem", "server.key")):
        return folder
    folder.mkdir(parents=True, exist_ok=True)
    _openssl(folder, "ecparam", "-name", "prime256v1", "-genkey", "-noout", "-out", "ca.key")
    _openssl(folder, "req", "-x509", "-new", "-key", "ca.key", "-sha256", "-days", "3650", "-subj", "/CN=jpreader test CA",
             "-addext", "basicConstraints=critical,CA:TRUE", "-addext", "keyUsage=critical,keyCertSign",
             "-addext", "subjectKeyIdentifier=hash", "-out", "ca.pem")
    _openssl(folder, "ecparam", "-name", "prime256v1", "-genkey", "-noout", "-out", "server.key")
    _openssl(folder, "req", "-new", "-key", "server.key", "-subj", "/CN=localhost", "-out", "server.csr")
    # strict verifiers (Python 3.13 and later) want both key identifiers
    (folder / "server.ext").write_text("subjectAltName=DNS:localhost\nbasicConstraints=CA:FALSE\n"
                                       "extendedKeyUsage=serverAuth\nsubjectKeyIdentifier=hash\n"
                                       "authorityKeyIdentifier=keyid\n")
    _openssl(folder, "x509", "-req", "-in", "server.csr", "-CA", "ca.pem", "-CAkey", "ca.key", "-CAcreateserial",
             "-days", "3650", "-sha256", "-extfile", "server.ext", "-out", "server.pem")
    return folder


def trusted_certificates(root: Path, debug: bool) -> list[Path]:
    """The roots the payload trusts: the public ones, and in debug builds the test CA too."""
    pems = certificate_files(root)
    return pems + [ensure_test_ca(root) / "ca.pem"] if debug else pems
