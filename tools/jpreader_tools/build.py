def game_header(constants: dict[str, int]) -> str:
    return "/* generated by jpreader_tools.build; do not edit */\n" + "".join(
        f"#define {name} 0x{value:08x}u\n" for name, value in sorted(constants.items()))


def generated_headers(code: bytes, builtin: bytes, exports: dict[str, int] | None = None) -> dict[str, str]:
    constants = game_constants(code)
    if exports is not None:
        constants.update(snd_constants(code, exports))
        constants.update(screen_constants(exports))
    return {"game_addrs.h": game_header(constants), "builtin_font.h": builtin_header(builtin)}


def read_env(root: Path, key: str) -> str | None:
    """A setting from the environment or .env; secrets among them are never printed."""
    import os

    if os.environ.get(key):
        return os.environ[key]
    env = root / ".env"
    if env.exists():
        for line in env.read_text().splitlines():
            if line.startswith(f"{key}="):
                return line.split("=", 1)[1].strip() or None
    return None



def notice(bearssl: Path) -> str:
    """NOTICE.txt: the data files' credits, and BearSSL's licence (code.ips contains BearSSL)."""
    return (NOTICE + "\ncode.ips contains BearSSL (https://bearssl.org/) under the MIT licence:\n\n"
            + (bearssl / "LICENSE.txt").read_text())

MOVE_NAMES, TYPE_NAMES, LAYOUT_STRINGS = 118, 112, 32      # system text files (docs/stage13-battle-findings.md)
COMMAND_LABELS = (4, 3, 5, 6)                              # たたかう, バッグ, ポケモン, にげる in file 32


def names_bin(rom) -> bytes:
    """names.bin (stage 13): English move and type names and a battle's command labels, beside the Japanese."""
    from .text import load_archive

    kana, kanji, english = (load_archive(rom, arc) for arc in (30, 31, 32))
    return formats.write_names([
        english[MOVE_NAMES],
        kana[TYPE_NAMES], kanji[TYPE_NAMES], english[TYPE_NAMES],
        *([a[LAYOUT_STRINGS][k] for k in COMMAND_LABELS] for a in (kana, kanji, english)),
    ])


ENGLISH_MAX = 160              # units of an English line kept for the peek (platform/screen.c EN_MAX)


def _english(units) -> list[int]:
    """An English line as the peek shows it: its literal text, line breaks as spaces, without tags."""
    from .text import Literal, parse_segments

    out: list[int] = []
    for segment in parse_segments(units):
        if not isinstance(segment, Literal):
            continue
        for u in segment.units:
            u = 0x20 if u in (0x0A, 0x0D) else u
            if u == 0x20 and (not out or out[-1] == 0x20):
                continue
            out.append(u)
    while out and out[-1] == 0x20:
        out.pop()
    return out[:ENGLISH_MAX]


def strings_bin(rom, literals=None) -> bytes:
    """strings.bin (stage 14): every system text line a screen can show, kana and kanji, by its key, with its English
    line and (stage 15) its literal translation from `literals` (key -> text, literal.Literals.items). Lines without
    tags come first, so a label or a name is found as itself, not as part of a template."""
    from .literal import units_for
    from .text import Tag, parse_segments, load_archive

    kana, kanji, english = (load_archive(rom, arc) for arc in (30, 31, 32))
    plain, tagged = [], []
    for archive in (kana, kanji):
        for file, lines in enumerate(archive):
            for line, units in enumerate(lines):
                key = formats.screen_key(units)
                if not key or len(key) > formats.SCREEN_KEY_MAX:
                    continue
                en = _english(english[file][line] if file < len(english) and line < len(english[file]) else [])
                row = (key, file, line, en, units_for(literals, key, en))
                has_tag = any(isinstance(s, Tag) for s in parse_segments(units))
                (tagged if has_tag else plain).append(row)
    return formats.write_strings(plain + tagged)


def build(root: Path, rom_path: Path, debug: bool) -> dict:
    kokoro_url, kokoro_token = read_env(root, "KOKORO_URL"), read_env(root, "KOKORO_TOKEN")
    with Rom(rom_path) as rom:
        rom.verify()
        code = rom.exefs_file(".code")
        exheader = rom.exheader()
        exports = parse_crs_exports(rom.romfs_file("static.crs"))
        code_sha = rom.code_sha256()
        chars = game_charset(rom)
        names = names_bin(rom)
        strings = strings_bin(rom, literal.Literals(literal.cache_path(root)).items)

    annot_bin, dict_bin, ids_bin = cached_files(root, rom_path, code_sha)
    font_bin, builtin = font_files(root / "build" / "cache", chars, dict_charset(*read_dict(dict_bin)))
    sites = plan_hooks(code, exports, debug)
    entry_target, entry_return = entry_redirect(code)
    bearssl = tls.fetch_bearssl(root / "build" / "cache")
    headers = generated_headers(code, builtin, exports)
    headers["trust_anchors.h"] = tls.trust_anchors_header(tls.build_brssl(bearssl), tls.trusted_certificates(root, debug))
    built = build_payload(root, sites, entry_target, entry_return, debug, headers, bearssl)
    trampolines = {site.name: built.symbols[f"jpr_tramp_{site.name}"] for site in sites}
    ips = build_patch(code, sites, trampolines, built.stub, built.payload, EDITS)
    voice_files, voice_report = build_voice(root)
    ids_path = root / "build" / "jpreader-ids.json"      # for kokoro's dictionary build (stage 9A): ids only
    ids_path.parent.mkdir(parents=True, exist_ok=True)
    ids_path.write_text(json.dumps({"jmdict": jmdict.JMDICT_RELEASE,
                                    "ids": sorted({i for i in read_ids(ids_bin)[1] if i})}) + "\n")
    write_dist(root / "dist", ips, patch_exheader(exheader, "luma"), patch_exheader(exheader, "azahar"),
               debug, {"font.bin": font_bin, "annot.bin": annot_bin, "dict.bin": dict_bin,
                       "ids.bin": ids_bin, "names.bin": names, "strings.bin": strings,
                       "NOTICE.txt": notice(bearssl).encode(), "config.txt": config_text(kokoro_url, kokoro_token).encode()},
               voice_files)

    info = {
        "debug": debug,
        "symbols": {name: built.symbols[name] for name in SYMBOLS if name in built.symbols},
        "payload_size": len(built.payload),
        "stub_size": len(built.stub),
        "font_bytes": len(font_bin),
        "annot_bytes": len(annot_bin),
        "dict_bytes": len(dict_bin),
        "kokoro_linked": bool(kokoro_url and kokoro_token),
        "voice": voice_report,
    }
    mode = "debug" if debug else "release"
    (root / "build" / f"build-info-{mode}.json").write_text(json.dumps(info, indent=1))
    return info
