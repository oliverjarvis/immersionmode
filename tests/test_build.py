ROOT = Path(__file__).resolve().parent.parent


def test_resolve_rom_prefers_argument(tmp_path, monkeypatch):
    monkeypatch.setenv("JPREADER_ROM", "/from/env.cci")
    assert cli.resolve_rom("/from/arg.cci", tmp_path) == Path("/from/arg.cci")


def test_resolve_rom_reads_env_file(tmp_path, monkeypatch):
    monkeypatch.delenv("JPREADER_ROM", raising=False)
    (tmp_path / ".env").write_text("OPENROUTER_API_KEY=secret\nJPREADER_ROM=/some/path (USA).cci\n")
    assert cli.resolve_rom(None, tmp_path) == Path("/some/path (USA).cci")


def test_resolve_rom_missing(tmp_path, monkeypatch):
    monkeypatch.delenv("JPREADER_ROM", raising=False)
    with pytest.raises(SystemExit, match="JPREADER_ROM"):
        cli.resolve_rom(None, tmp_path)


SD = {"font.bin": b"JPRF", "annot.bin": b"JPRA", "dict.bin": b"JPRW", "NOTICE.txt": b"notice"}


def test_debug_build_is_never_written_for_the_3ds(tmp_path):
    written = package.write_dist(tmp_path, b"PATCHEOF", bytes(0x400), bytes(0x800), True, SD)
    assert sorted(p.name for p in tmp_path.iterdir()) == ["azahar-debug"]
    assert len(written) == 2 + len(SD)
    for name, data in SD.items():
        assert (tmp_path / "azahar-debug" / "sdmc" / "jpreader" / name).read_bytes() == data


def test_release_build_writes_3ds_and_azahar_folders(tmp_path):
    package.write_dist(tmp_path, b"PATCHEOF", bytes(0x400), bytes(0x800), False, SD)
    assert sorted(p.name for p in tmp_path.iterdir()) == ["3ds", "azahar"]
    assert (tmp_path / "3ds" / "luma" / "titles" / TITLE_ID_STR / "code.ips").read_bytes() == b"PATCHEOF"
    for name, data in SD.items():
        assert (tmp_path / "3ds" / "jpreader" / name).read_bytes() == data
        assert (tmp_path / "azahar" / "sdmc" / "jpreader" / name).read_bytes() == data


