def test_large_files_are_linked_not_copied_and_old_parts_go(tmp_path):
    big = tmp_path / "build" / "voice"
    big.mkdir(parents=True)
    (big / "voice.bin").write_bytes(b"JPRV index")
    (big / "voice-0.bin").write_bytes(b"samples")
    stale = tmp_path / "dist" / "3ds" / "jpreader" / "voice-7.bin"
    stale.parent.mkdir(parents=True)
    stale.write_bytes(b"from an older build")
    links = {"voice.bin": big / "voice.bin", "voice-0.bin": big / "voice-0.bin"}
    package.write_dist(tmp_path / "dist", b"PATCHEOF", bytes(0x400), bytes(0x800), False, SD, links)
    for where in ("3ds/jpreader", "azahar/sdmc/jpreader"):
        target = tmp_path / "dist" / where / "voice-0.bin"
        assert target.read_bytes() == b"samples" and target.stat().st_ino == (big / "voice-0.bin").stat().st_ino
    assert not stale.exists()
