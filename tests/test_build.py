@pytest.mark.rom
def test_debug_build_end_to_end(rom_path, rom):
    info = build.build(ROOT, rom_path, debug=True)
    mods = ROOT / "dist" / "azahar-debug" / "load" / "mods" / TITLE_ID_STR
    ips_bytes = (mods / "exefs" / "code.ips").read_bytes()
    assert len((mods / "exheader.bin").read_bytes()) == 0x800

    image = apply_ips(rom.exefs_file(".code"), ips_bytes)
    entry = struct.unpack_from("<I", image, 0)[0]
    assert entry >> 24 == 0xEA and CODE_BASE + 8 + (entry & 0xFFFFFF) * 4 == STUB_BASE
    assert info["symbols"]["jpr_init"] == PAYLOAD_BASE
    assert json.loads((ROOT / "build" / "build-info-debug.json").read_text()) == info

    assert info["font_bytes"] > 150_000
    assert "jpr_panel" in info["symbols"]
    sd = ROOT / "dist" / "azahar-debug" / "sdmc" / "jpreader"
    assert info["annot_bytes"] > 1_000_000 and (sd / "annot.bin").stat().st_size == info["annot_bytes"]
    assert (sd / "dict.bin").stat().st_size == info["dict_bytes"]
    config = (sd / "config.txt").read_text()
    assert config.startswith("debug=0\n") and "api_key" not in config
    assert "kokoro_token" not in json.dumps(info)
    assert "JMdict" in (sd / "NOTICE.txt").read_text()
    stamp, ids, pairs = formats.read_ids((sd / "ids.bin").read_bytes())
    assert stamp == struct.unpack_from("<I", (sd / "dict.bin").read_bytes(), 24)[0] and sum(1 for i in ids if i) > 9000
    assert len(pairs) > len([i for i in ids if i])                    # every spelling of each word
    entries, _labels = formats.read_dict((sd / "dict.bin").read_bytes())
    assert [e.jmdict_id if e.kind == "dictionary" else 0 for e in entries] == ids   # dict.bin v3 carries them too
    assert not (sd / "heads.bin").exists()
    assert len(json.loads((ROOT / "build" / "jpreader-ids.json").read_text())["ids"]) > 9000
    assert "BearSSL" in (sd / "NOTICE.txt").read_text() and "Thomas Pornin" in (sd / "NOTICE.txt").read_text() and "Noto Sans JP" in (sd / "NOTICE.txt").read_text()
    assert (ROOT / "dist" / "azahar-debug" / "sdmc" / "jpreader" / "font.bin").stat().st_size == info["font_bytes"]

@pytest.mark.rom
def test_release_build_writes_both_targets(rom_path):
    build.build(ROOT, rom_path, debug=False)
    luma = ROOT / "dist" / "3ds" / "luma" / "titles" / TITLE_ID_STR
    azahar = ROOT / "dist" / "azahar" / "load" / "mods" / TITLE_ID_STR
    assert len((luma / "exheader.bin").read_bytes()) == 0x400
    assert len((azahar / "exheader.bin").read_bytes()) == 0x800
    assert (luma / "code.ips").read_bytes() == (azahar / "exefs" / "code.ips").read_bytes()


@pytest.mark.rom
def test_release_build_ships_the_game_edits(rom_path, rom):
    import struct

    from jpreader_tools.ips import apply_ips
    from jpreader_tools.layout import CODE_BASE
    from jpreader_tools.patch import EDITS

    build.build(ROOT, rom_path, debug=False)
    ips = (ROOT / "dist" / "3ds" / "luma" / "titles" / TITLE_ID_STR / "code.ips").read_bytes()
    image = apply_ips(rom.exefs_file(".code"), ips)
    for edit in EDITS:
        assert struct.unpack_from("<I", image, edit.addr - CODE_BASE)[0] == edit.replacement, edit.name


def test_config_text():
    text = package.config_text("https://k.example", "kkr_t")
    assert text == "debug=0\nkokoro_url=https://k.example\nkokoro_token=kkr_t\n"
